/**
 * Generates the BetterAuth schema SQL for Postgres from `getAuthTables`
 * and (optionally) applies it to the configured database.
 *
 * Replaces the deprecated @better-auth/cli (v1.4.x) whose adapter detection
 * is incompatible with better-auth 1.7.10.
 *
 * Usage:
 *   npx ts-node scripts/generate-auth-schema.ts            → print SQL
 *   npx ts-node scripts/generate-auth-schema.ts --apply    → write to DB + save file
 */
import 'dotenv/config';
import { resolve } from 'path';
import { configuration } from '../src/config/configuration';
import { buildAuth } from '../src/modules/auth/better-auth.instance';
import type { MailService } from '../src/modules/mail/mail.service';
import { getAuthTables } from 'better-auth';

type FieldType = 'string' | 'number' | 'boolean' | 'date';

interface FieldDef {
  type: FieldType;
  required?: boolean;
  unique?: boolean;
  fieldName: string;
  references?: { model: string; field: string; onDelete?: string };
  index?: boolean;
  bigserial?: boolean;
}

interface TableDef {
  modelName: string;
  fields: Record<string, FieldDef>;
  order?: number;
}

const PG_TYPE: Record<FieldType, string> = {
  string: 'text',
  number: 'integer',
  boolean: 'boolean',
  date: 'timestamptz',
};

const snake = (camel: string): string =>
  camel.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function tablesToSql(tables: Record<string, TableDef>): string {
  const sorted = Object.values(tables).sort((a, b) => (a.order ?? 99) - (b.order ?? 99));
  const parts: string[] = [];

  for (const table of sorted) {
    const tableName = snake(table.modelName);
    const lines: string[] = [];

    // BetterAuth's `id` column is implicit in getAuthTables — always PK, text.
    lines.push(`  "id" text NOT NULL PRIMARY KEY`);

    for (const [key, field] of Object.entries(table.fields)) {
      const colName = quoteIdent(field.fieldName ?? snake(key));
      const nullClause = field.required === true ? 'NOT NULL' : 'NULL';
      const uniqueClause = field.unique === true ? ' UNIQUE' : '';
      const idx = field.references;
      const refClause = idx
        ? ` REFERENCES ${quoteIdent(snake(idx.model))} (${quoteIdent(snake(idx.field))})`
        : '';
      lines.push(`  ${colName} ${PG_TYPE[field.type]} ${nullClause}${uniqueClause}${refClause}`);
    }
    parts.push(
      `CREATE TABLE IF NOT EXISTS ${quoteIdent(tableName)} (\n${lines.join(',\n')}\n);`,
    );

    for (const [key, field] of Object.entries(table.fields)) {
      if (field.index === true) {
        parts.push(
          `CREATE INDEX IF NOT EXISTS ${quoteIdent(`idx_${tableName}_${field.fieldName ?? snake(key)}`)}`
            + ` ON ${quoteIdent(tableName)} (${quoteIdent(field.fieldName ?? snake(key))});`,
        );
      }
    }
  }

  return `-- BetterAuth schema (generated by scripts/generate-auth-schema.ts — do not edit by hand)\n\n${parts.join('\n\n')}\n`;
}

/**
 * Idempotent additive evolution for auth tables that ALREADY exist in a
 * deployed database — `CREATE TABLE IF NOT EXISTS` cannot extend them. Covers
 * plugin-added nullable columns (e.g. the username plugin's `user.username`).
 * Required columns (email, emailVerified, ...) are NOT covered: they always
 * exist because they come from base BetterAuth and cannot be added retroactively.
 */
function evolutionSql(tables: Record<string, TableDef>): string {
  const parts: string[] = [];
  for (const table of Object.values(tables).sort((a, b) => (a.order ?? 99) - (b.order ?? 99))) {
    const tableName = quoteIdent(snake(table.modelName));
    for (const [key, field] of Object.entries(table.fields)) {
      if (field.required === true) continue;
      const colName = quoteIdent(field.fieldName ?? snake(key));
      parts.push(`ALTER TABLE ${tableName} ADD COLUMN IF NOT EXISTS ${colName} ${PG_TYPE[field.type]};`);
      if (field.unique === true) {
        parts.push(
          `CREATE UNIQUE INDEX IF NOT EXISTS ${quoteIdent(`uq_${snake(table.modelName)}_${field.fieldName ?? snake(key)}`)}`
            + ` ON ${tableName} (${colName});`,
        );
      } else if (field.index === true) {
        parts.push(
          `CREATE INDEX IF NOT EXISTS ${quoteIdent(`idx_${snake(table.modelName)}_${field.fieldName ?? snake(key)}`)}`
            + ` ON ${tableName} (${colName});`,
        );
      }
    }
  }
  return parts.join('\n');
}

async function apply(createSql: string, alterSql: string | null): Promise<void> {
  const { Client } = await import('pg');
  const { sslFromUrl } = await import('../src/database/ssl');
  const url = process.env.DATABASE_URL ?? '';
  const client = new Client({ connectionString: url, ssl: sslFromUrl(url) || undefined });
  await client.connect();
  await client.query(createSql);
  // Additive evolution is applied WITH --apply only: it may leave a printed SQL
  // script confusing if interleaved with fresh-install CREATE statements.
  if (alterSql) await client.query(alterSql);
  const { rows } = await client.query<{ n: number }>(
    `SELECT count(*)::int AS n FROM information_schema.tables
     WHERE table_schema = 'public' AND table_name IN ('user','session','account','verification')`,
  );
  console.log(`applied — auth tables now present: ${rows[0].n}/4`);
  await client.end();
}

async function main(): Promise<void> {
  // CLI context: buildAuth requires a MailService dep — never called here
  // (schema generation only reads auth.options, no mail can fire).
  const mailStub = {
    send: async () => false,
    sendVerificationEmail: async () => false,
    sendResetPassword: async () => false,
  } as unknown as MailService;
  const auth = buildAuth({ config: configuration(), mail: mailStub });
  const applyFlag = process.argv.includes('--apply');
  const tables = getAuthTables(auth.options) as unknown as Record<string, TableDef>;
  const sql = tablesToSql(tables);
  const sqlWithEvolution = `${sql}\n-- additive evolution for deployed databases\n${evolutionSql(tables)}\n`;
  console.log(sqlWithEvolution);

  if (applyFlag) {
    await apply(sql, evolutionSql(tables));
    const { writeFileSync, mkdirSync } = await import('fs');
    mkdirSync(resolve('docs', 'schema'), { recursive: true });
    writeFileSync(resolve('docs', 'schema', 'better-auth-schema.sql'), sqlWithEvolution, 'utf8');
    console.log('saved reference to docs/schema/better-auth-schema.sql');
  }
}

void main().catch((err) => {
  console.error('SCHEMA GENERATION FAILED:', err instanceof Error ? err.message : err);
  process.exit(1);
});
